"""共用的数值常量 —— 它们本身没有任何领域含义，只是两个模块恰好都要用。

**为什么单独一个模块。** ``accumulate``（通用多帧累积）和 ``baseline``（基准面
拟合，属于风团研究）都要把 MAD 换算成 sigma。把 ``MAD_TO_SIGMA`` 留在
``metrics``（风团指标）里，通用累积就被迫 import 领域模块——依赖方向就反了。
放在这个叶子模块里，两个方向谁都不依赖谁。

刻意**只放常量，不放计算函数**。两处的用法看着像，实际不同：

- ``baseline`` 的 ``residuals`` 已经去过中心，算的是 ``median(|residuals|)``；
- ``accumulate`` 要先对栈居中，而且算出的 ``|stack - center|`` **还要继续用于
  剔除离群值**，不能被包进一个内部再算一次绝对值的函数里。

任何“顺手统一一下”的辅助函数都会把其中一处变错或变浪费，所以只共享常量。
"""

from __future__ import annotations

#: ``sigma ≈ MAD_TO_SIGMA × MAD``。
#:
#: 不是经验系数：1.4826 = ``1 / Φ⁻¹(0.75)``，即正态分布下 MAD 与 sigma 的精确比值。
#: 对重尾分布比标准差稳健（崩溃点 50% vs 0%），但**前提是噪声大致对称**——
#: 单边截断的分布上它会系统性低估 sigma。本相机的噪声恰好是重尾的
#: （实测 ``std / (MAD×1.4826) ≈ 1.9``），这正是累积降噪远达不到 1/√N 的原因。
MAD_TO_SIGMA = 1.4826
